CREATE TABLE ACCTDAT (
    ACCT_ID BIGINT PRIMARY KEY,
    ACCT_VERSION BIGINT NOT NULL,
    ACCT_ACTIVE_STATUS VARCHAR(1),
    ACCT_CURR_BAL NUMERIC(12, 2),
    ACCT_CREDIT_LIMIT NUMERIC(12, 2),
    ACCT_CASH_CREDIT_LIMIT NUMERIC(12, 2),
    ACCT_OPEN_DATE VARCHAR(10),
    ACCT_EXPIRAION_DATE VARCHAR(10),
    ACCT_REISSUE_DATE VARCHAR(10),
    ACCT_CURR_CYC_CREDIT NUMERIC(12, 2),
    ACCT_CURR_CYC_DEBIT NUMERIC(12, 2),
    ACCT_ADDR_ZIP VARCHAR(10),
    ACCT_GROUP_ID VARCHAR(10)
);

CREATE TABLE CUSTDAT (
    CUST_ID BIGINT PRIMARY KEY,
    CUST_VERSION BIGINT NOT NULL,
    CUST_FIRST_NAME VARCHAR(25),
    CUST_MIDDLE_NAME VARCHAR(25),
    CUST_LAST_NAME VARCHAR(25),
    CUST_ADDR_LINE_1 VARCHAR(50),
    CUST_ADDR_LINE_2 VARCHAR(50),
    CUST_ADDR_LINE_3 VARCHAR(50),
    CUST_ADDR_STATE_CD VARCHAR(2),
    CUST_ADDR_COUNTRY_CD VARCHAR(3),
    CUST_ADDR_ZIP VARCHAR(10),
    CUST_PHONE_NUM_1 VARCHAR(15),
    CUST_PHONE_NUM_2 VARCHAR(15),
    CUST_SSN VARCHAR(9),
    CUST_GOVT_ISSUED_ID VARCHAR(20),
    CUST_DOB_YYYY_MM_DD VARCHAR(10),
    CUST_EFT_ACCOUNT_ID VARCHAR(10),
    CUST_PRI_CARD_HOLDER_IND VARCHAR(1),
    CUST_FICO_CREDIT_SCORE INTEGER
);

CREATE TABLE TRANTYPE (
    TRAN_TYPE VARCHAR(2) PRIMARY KEY,
    TRAN_TYPE_DESC VARCHAR(50)
);

CREATE TABLE TRANCATG (
    TRAN_TYPE_CD VARCHAR(2) NOT NULL,
    TRAN_CAT_CD INTEGER NOT NULL,
    TRAN_CAT_TYPE_DESC VARCHAR(50),
    PRIMARY KEY (TRAN_TYPE_CD, TRAN_CAT_CD),
    CONSTRAINT FK_TRANCATG_TYPE FOREIGN KEY (TRAN_TYPE_CD) REFERENCES TRANTYPE (TRAN_TYPE)
);

CREATE TABLE CARDDAT (
    CARD_NUM VARCHAR(16) PRIMARY KEY,
    CARD_VERSION BIGINT NOT NULL,
    CARD_ACCT_ID BIGINT NOT NULL,
    CARD_CVV_CD INTEGER,
    CARD_EMBOSSED_NAME VARCHAR(50),
    CARD_EXPIRAION_DATE VARCHAR(10),
    CARD_ACTIVE_STATUS VARCHAR(1),
    CONSTRAINT FK_CARDDAT_ACCOUNT FOREIGN KEY (CARD_ACCT_ID) REFERENCES ACCTDAT (ACCT_ID)
);

CREATE TABLE CCXREF (
    XREF_CARD_NUM VARCHAR(16) PRIMARY KEY,
    XREF_CUST_ID BIGINT NOT NULL,
    XREF_ACCT_ID BIGINT NOT NULL,
    CONSTRAINT FK_CCXREF_CARD FOREIGN KEY (XREF_CARD_NUM) REFERENCES CARDDAT (CARD_NUM),
    CONSTRAINT FK_CCXREF_CUSTOMER FOREIGN KEY (XREF_CUST_ID) REFERENCES CUSTDAT (CUST_ID),
    CONSTRAINT FK_CCXREF_ACCOUNT FOREIGN KEY (XREF_ACCT_ID) REFERENCES ACCTDAT (ACCT_ID)
);

CREATE TABLE TCATBALF (
    TRANCAT_ACCT_ID BIGINT NOT NULL,
    TRANCAT_TYPE_CD VARCHAR(2) NOT NULL,
    TRANCAT_CD INTEGER NOT NULL,
    TRAN_CAT_BAL NUMERIC(11, 2),
    PRIMARY KEY (TRANCAT_ACCT_ID, TRANCAT_TYPE_CD, TRANCAT_CD),
    CONSTRAINT FK_TCATBALF_ACCOUNT FOREIGN KEY (TRANCAT_ACCT_ID) REFERENCES ACCTDAT (ACCT_ID),
    CONSTRAINT FK_TCATBALF_CATEGORY FOREIGN KEY (TRANCAT_TYPE_CD, TRANCAT_CD)
        REFERENCES TRANCATG (TRAN_TYPE_CD, TRAN_CAT_CD)
);

CREATE TABLE DISCGRP (
    DIS_ACCT_GROUP_ID VARCHAR(10) NOT NULL,
    DIS_TRAN_TYPE_CD VARCHAR(2) NOT NULL,
    DIS_TRAN_CAT_CD INTEGER NOT NULL,
    DIS_INT_RATE NUMERIC(6, 2),
    PRIMARY KEY (DIS_ACCT_GROUP_ID, DIS_TRAN_TYPE_CD, DIS_TRAN_CAT_CD),
    CONSTRAINT FK_DISCGRP_CATEGORY FOREIGN KEY (DIS_TRAN_TYPE_CD, DIS_TRAN_CAT_CD)
        REFERENCES TRANCATG (TRAN_TYPE_CD, TRAN_CAT_CD)
);

CREATE TABLE TRANSACT (
    TRAN_ID VARCHAR(16) PRIMARY KEY,
    TRAN_TYPE_CD VARCHAR(2) NOT NULL,
    TRAN_CAT_CD INTEGER NOT NULL,
    TRAN_SOURCE VARCHAR(10),
    TRAN_DESC VARCHAR(100),
    TRAN_AMT NUMERIC(11, 2),
    TRAN_MERCHANT_ID BIGINT,
    TRAN_MERCHANT_NAME VARCHAR(50),
    TRAN_MERCHANT_CITY VARCHAR(50),
    TRAN_MERCHANT_ZIP VARCHAR(10),
    TRAN_CARD_NUM VARCHAR(16) NOT NULL,
    TRAN_ORIG_TS VARCHAR(26),
    TRAN_PROC_TS VARCHAR(26),
    CONSTRAINT FK_TRANSACT_TYPE FOREIGN KEY (TRAN_TYPE_CD) REFERENCES TRANTYPE (TRAN_TYPE),
    CONSTRAINT FK_TRANSACT_CATEGORY FOREIGN KEY (TRAN_TYPE_CD, TRAN_CAT_CD)
        REFERENCES TRANCATG (TRAN_TYPE_CD, TRAN_CAT_CD),
    CONSTRAINT FK_TRANSACT_CARD FOREIGN KEY (TRAN_CARD_NUM) REFERENCES CARDDAT (CARD_NUM)
);

CREATE TABLE USRSEC (
    SEC_USR_ID VARCHAR(8) PRIMARY KEY,
    SEC_USR_FNAME VARCHAR(20),
    SEC_USR_LNAME VARCHAR(20),
    SEC_USR_PWD VARCHAR(8),
    SEC_USR_TYPE VARCHAR(1)
);

CREATE TABLE TRAN_ID_ALLOCATION (
    ALLOCATION_KEY VARCHAR(20) PRIMARY KEY,
    LAST_ALLOCATED_ID BIGINT NOT NULL,
    ALLOCATION_VERSION BIGINT NOT NULL
);

CREATE TABLE REPORT_REQUEST (
    REPORT_REQUEST_ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    REPORT_TYPE VARCHAR(10) NOT NULL,
    START_DATE DATE NOT NULL,
    END_DATE DATE NOT NULL,
    STATUS VARCHAR(12) NOT NULL,
    SUBMITTED_AT TIMESTAMP NOT NULL
);

CREATE INDEX IDX_CARDDAT_ACCOUNT ON CARDDAT (CARD_ACCT_ID);
CREATE INDEX IDX_CCXREF_ACCOUNT ON CCXREF (XREF_ACCT_ID);
CREATE INDEX IDX_CCXREF_CUSTOMER ON CCXREF (XREF_CUST_ID);
CREATE INDEX IDX_TCATBALF_CATEGORY ON TCATBALF (TRANCAT_TYPE_CD, TRANCAT_CD);
CREATE INDEX IDX_DISCGRP_CATEGORY ON DISCGRP (DIS_TRAN_TYPE_CD, DIS_TRAN_CAT_CD);
CREATE INDEX IDX_DISCGRP_ACCOUNT_GROUP ON DISCGRP (DIS_ACCT_GROUP_ID);
CREATE INDEX IDX_TRANSACT_CARD ON TRANSACT (TRAN_CARD_NUM);
CREATE INDEX IDX_TRANSACT_REPORT ON TRANSACT (TRAN_PROC_TS, TRAN_CARD_NUM);
CREATE INDEX IDX_REPORT_REQUEST_STATUS ON REPORT_REQUEST (STATUS, SUBMITTED_AT);
